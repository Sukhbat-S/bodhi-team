import { mkdir, copyFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(packageRoot, "../..");
const defaultOutput = path.join(
  repositoryRoot,
  "integrations/codex-plugin/bodhi/mcp/server.cjs",
);

export async function buildCodexPlugin(outfile = defaultOutput) {
  await mkdir(path.dirname(outfile), { recursive: true });
  await copyFile(path.join(repositoryRoot, "scripts/lib/bodhi-node.sh"), path.join(path.dirname(outfile), "runtime.sh"));
  await build({
    absWorkingDir: repositoryRoot,
    entryPoints: ["packages/mcp-server/src/index.ts"],
    outfile,
    bundle: true,
    format: "cjs",
    platform: "node",
    target: "node20",
    treeShaking: true,
    preserveSymlinks: true,
    alias: {
      "@seneca/core": "./packages/core/src/index.ts",
    },
    legalComments: "none",
    banner: {
      js: "// Generated by npm run build:codex-plugin --workspace=@seneca/mcp-server. Do not edit.",
    },
  });
}

const outputFlag = process.argv.indexOf("--output");
const output = outputFlag >= 0 ? process.argv[outputFlag + 1] : undefined;
if (outputFlag >= 0 && !output) throw new Error("--output requires a file path");
await buildCodexPlugin(output ? path.resolve(output) : undefined);
